import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { FrontendConfig } from '../config';
import { renderFrontendTheme } from './render';

const library = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export function generateFrontendTheme(settings: FrontendConfig, spacingValues: readonly number[] = []): number {
    const rendered = renderFrontendTheme(settings, spacingValues);
    const outputs = [
        ['src/core/theme.css', rendered.css],
        ['src/core/theme.generated.ts', rendered.runtime],
        ['src/core/_responsive-generated.scss', rendered.breakpoints],
        ['src/core/_typography-generated.scss', rendered.typographyScss],
        ['src/core/scale.ts', "// AUTO-GENERATED by Frontend.\nimport { FRONTEND_THEME } from './theme.generated';\nexport const SCALE = FRONTEND_THEME.responsive;\n"],
        ['src/skin/_tokens.scss', rendered.skin.tokens],
        ['src/skin/_classes.scss', rendered.skin.classes],
    ] as const;
    let changed = 0;
    for (const [relative, content] of outputs) {
        const file = path.join(library, relative);
        if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === content) continue;
        fs.mkdirSync(path.dirname(file), { recursive: true });
        fs.writeFileSync(file, content, 'utf8');
        changed++;
    }
    return changed;
}
