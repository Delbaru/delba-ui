export interface TextRevealOptions {
  /** Длительность анимации одной буквы, сек. */
  duration?: number;
  /** Задержка между соседними буквами (волна), сек. */
  stagger?: number;
  /** Вертикальный сдвиг буквы на старте/финише, em. */
  shift?: number;
  /**
   * Потолок суммарной длительности волны, сек (по умолчанию 0.9). На длинном тексте разброс задержек между
   * буквами сжимается, чтобы уложиться в этот бюджет — иначе многострочный ревил тянулся бы секундами.
   */
  maxDuration?: number;
}
