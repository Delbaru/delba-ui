/** A preset is visual data. Native attributes, refs and event handlers remain instance props. */
export type PresetStyle<P> = Partial<Pick<P, Extract<keyof P, VisualKey | NativeVisualKey>>>;
/** Native multi-surface configuration is resolved by its owner; state styles target the surface. */
export type PresetStates<P> = Readonly<
    Record<string, Partial<Pick<P, Extract<keyof P, VisualKey>>> | undefined>
>;
export type Preset<P> = PresetStyle<P> & { readonly states?: PresetStates<P> };
export type PresetMap<P> = Readonly<Record<string, Preset<P>>>;
export interface PresetProps<P> {
    preset?: Preset<P>;
    states?: PresetStates<P>;
}

export interface PresetOptions {
    /** Input/Textarea keep layout on their root and paint their marked control surface. */
    target?: 'root' | 'field';
}
